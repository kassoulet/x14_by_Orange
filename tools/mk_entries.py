#!/usr/bin/env python3
"""mk_entries.py FX=ORACLE_PREFIX ...: web/fx/entries.js from oracle2bin.py captures. The harness' grid-aligned entry E (music s on the MODEL timeline re/s3mtime.model.json)
is stored as (order,row,dt) so it can be re-expressed on the libopenmpt timeline the player uses (at(order,row)+dt)."""
import sys, json, bisect
rows = json.load(open(__file__.rsplit('/', 2)[0] + '/re/s3mtime.model.json'))['rows']; TS = [r[3] for r in rows]
out = json.loads(open(__file__.rsplit('/', 2)[0] + '/web/fx/entries.js').read().split('ENTRY = ')[1].split(';')[0])   # keep the other effects' entries
for a in sys.argv[1:]:
    fx, pre = a.split('='); J = json.load(open(pre + '.json'))
    # pass-type captures (fx7, fx9: list of passes): E = music time of the loop top of pass 0 (top[19] = virtual time there; t0 = vt - mt)
    E = J['E'] if isinstance(J, dict) else J[0]['top'][-4] - (J[0]['vt'] - J[0]['mt'])
    k = bisect.bisect_right(TS, E) - 1
    out[fx] = [rows[k][0], rows[k][2], round(E - rows[k][3], 5)]
open(__file__.rsplit('/', 2)[0] + '/web/fx/entries.js', 'w').write('// generated by tools/mk_entries.py - do not edit\n// harness (Unicorn virtual clock) measurement of the first fade-in palette upload of each ported effect: [order, row, seconds after that row start]\n'
    'import { at } from \'./timeline.js\';\nexport const ENTRY = %s;\nexport const entryTime = fx => at(ENTRY[fx][0], ENTRY[fx][1]) + ENTRY[fx][2];\n' % json.dumps(out))
print(out)
