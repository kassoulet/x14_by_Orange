#!/usr/bin/env python3
"""mk_timeline.py: re/s3mtime.json (S3M walk: order,pattern,row,start time) -> web/fx/timeline.js (pos(t) -> {order,row,t0}).
Music t=0 = entry of effect 0. Model agrees with libopenmpt's duration within 0.2 s (250.94 vs 251.1)."""
import json,os
H=os.path.dirname(os.path.abspath(__file__)); rows=json.load(open(H+'/../re/s3mtime.json'))['rows']
o=['// generated by tools/mk_timeline.py - do not edit','export const ROWS=%s; // [order,pattern,row,start_s]'%json.dumps(rows,separators=(',',':')),
'''export function pos(t){let lo=0,hi=ROWS.length-1;while(lo<hi){const m=(lo+hi+1)>>1;if(ROWS[m][3]<=t)lo=m;else hi=m-1}
const r=ROWS[lo];return{order:r[0],pattern:r[1],row:r[2],t0:r[3],i:lo}}
// start time of (order,row): first visit
export function at(order,row){for(const r of ROWS)if(r[0]===order&&r[2]>=row)return r[3];return Infinity}''']
open(H+'/../web/fx/timeline.js','w').write('\n'.join(o)+'\n')
